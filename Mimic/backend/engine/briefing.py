def _resolved_choices_from_current_brief(current_brief: Optional[Dict[str, Any]]) -> List[str]:
    if not isinstance(current_brief, dict):
        return []

    answers = current_brief.get("clarification_answers")
    if not isinstance(answers, dict):
        return []

    question_lookup: Dict[str, str] = {}
    for question in current_brief.get("questions") or []:
        if isinstance(question, dict):
            qid = str(question.get("id") or "").strip()
            qtext = str(question.get("question") or "").strip()
            if qid and qtext:
                question_lookup[qid] = qtext

    resolved: List[str] = []
    for key, answer in answers.items():
        clean_answer = sanitize_plain_text(str(answer).strip(), 100)
        if not clean_answer:
            continue
        question_text = question_lookup.get(str(key), "")
        if question_text:
            resolved.append(f"{sanitize_plain_text(question_text, 90)}: {clean_answer}")
        else:
            resolved.append(clean_answer)

    return resolved[:4]


def normalize_brief(data: Dict[str, Any], message: str, current_brief: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
    fallback = _fallback_brief(message)
    questions = _as_question_list(data.get("questions"))
    legacy_question = sanitize_plain_text(_safe_text(data.get("question"), "", 180), 180)
    if legacy_question and not questions:
        questions = [{
            "id": "creative_choice",
            "question": legacy_question,
            "options": [],
            "impact": "This helps MIMIC avoid guessing the edit direction.",
        }]

    intake = _normalize_intake(data.get("intake"))
    intake_confidence = _normalize_confidence(data.get("intake_confidence"))
    has_answers = _has_clarification_answers(current_brief)
    if not has_answers:
        questions = _auto_questions_for_intake(intake_confidence, questions)

    status = str(data.get("status") or "").strip().lower()
    if status not in {"needs_clarification", "ready_for_approval"}:
        status = "needs_clarification" if questions else "ready_for_approval"
    if questions and not has_answers:
        status = "needs_clarification"
    if status == "needs_clarification" and not questions:
        status = "ready_for_approval"
    resolved_choices = [
        sanitize_plain_text(v, 160)
        for v in _as_list(data.get("resolved_choices"), _resolved_choices_from_current_brief(current_brief))[:4]
    ]

    production_prompt = _ensure_production_prompt_context(
        sanitize_plain_text(_safe_text(data.get("production_prompt"), fallback["production_prompt"], 2400), 2400),
        intake,
        resolved_choices,
    )

    brief = {
        "status": status,
        "summary": sanitize_plain_text(_safe_text(data.get("summary"), fallback["summary"], 180), 180),
        "assumptions": [sanitize_plain_text(v, 120) for v in _as_list(data.get("assumptions"), fallback["assumptions"])[:4]],
        "resolved_choices": resolved_choices,
        "intake": intake,
        "intake_confidence": intake_confidence,
        "vibe": [sanitize_plain_text(v, 60) for v in _as_list(data.get("vibe"), fallback["vibe"])[:4]],
        "pacing": sanitize_plain_text(_safe_text(data.get("pacing"), fallback["pacing"], 180), 180),
        "clip_preferences": [sanitize_plain_text(v, 100) for v in _as_list(data.get("clip_preferences"), fallback["clip_preferences"])[:6]],
        "avoid": [sanitize_plain_text(v, 100) for v in _as_list(data.get("avoid"), fallback["avoid"])[:5]],
        "text_style": sanitize_plain_text(_safe_text(data.get("text_style"), fallback["text_style"], 180), 180),
        "music_direction": sanitize_plain_text(_safe_text(data.get("music_direction"), fallback["music_direction"], 180), 180),
        "question": questions[0]["question"] if questions else "",
        "questions": questions,
        "production_prompt": production_prompt,
    }

    return brief


def generate_creative_brief(message: str, current_brief: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
    if not message.strip():
        raise ValueError("Message is required")

    prompt = BRIEF_PROMPT_TEMPLATE.format(
        message=message.strip(),
        current_brief=json.dumps(current_brief or {}, ensure_ascii=True, indent=2),
    )

    try:
        data = call_deepseek_v3(
            prompt=prompt,
            system_prompt=BRIEF_SYSTEM_PROMPT,
        )
        return normalize_brief(data, message, current_brief)
    except Exception as exc:
        print(f"[BRIEF] DeepSeek brief generation failed, using fallback: {exc}")
        return _fallback_brief(message)

