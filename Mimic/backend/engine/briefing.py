def _as_list(value: Any, fallback: List[str]) -> List[str]:
    if isinstance(value, list):
        cleaned = [str(item).strip() for item in value if str(item).strip()]
        return cleaned[:6] or fallback
    if isinstance(value, str) and value.strip():
        return [value.strip()]
    return fallback


def _safe_text(value: Any, fallback: str, limit: int = 800) -> str:
    text = str(value or "").strip()
    if not text:
        return fallback
    return text[:limit]


def _as_question_list(value: Any) -> List[Dict[str, Any]]:
    if not isinstance(value, list):
        return []

    questions: List[Dict[str, Any]] = []
    seen_ids = set()
    for index, item in enumerate(value):
        if not isinstance(item, dict):
            continue

        question = sanitize_plain_text(_safe_text(item.get("question"), "", 180), 180)
        if not question:
            continue

        raw_id = _safe_text(item.get("id"), f"decision_{index + 1}", 60).lower()
        question_id = "".join(ch if ch.isalnum() else "_" for ch in raw_id).strip("_") or f"decision_{index + 1}"
        if question_id in seen_ids:
            question_id = f"{question_id}_{index + 1}"
        seen_ids.add(question_id)

        options = [
            sanitize_plain_text(str(option).strip(), 90)
            for option in _as_list(item.get("options"), [])
            if str(option).strip()
        ][:4]

        questions.append({
            "id": question_id,
            "field": sanitize_plain_text(_safe_text(item.get("field"), "", 80), 80),
            "question": question,
            "options": options,
            "impact": sanitize_plain_text(_safe_text(item.get("impact"), "", 160), 160),
        })

    return questions[:4]


