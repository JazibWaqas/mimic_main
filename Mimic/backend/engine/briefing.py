def _normalize_intake(data: Any) -> Dict[str, str]:
    raw = data if isinstance(data, dict) else {}
    return {
        field: sanitize_plain_text(_safe_text(raw.get(field), config["fallback"], 220), 220)
        for field, config in INTAKE_FIELDS.items()
    }


def _normalize_confidence(data: Any) -> Dict[str, str]:
    raw = data if isinstance(data, dict) else {}
    confidence: Dict[str, str] = {}
    for field in INTAKE_FIELDS:
        value = str(raw.get(field) or "").strip().lower()
        confidence[field] = value if value in {"confirmed", "assumed", "missing"} else "assumed"
    return confidence


def _has_clarification_answers(current_brief: Optional[Dict[str, Any]]) -> bool:
    return isinstance(current_brief, dict) and isinstance(current_brief.get("clarification_answers"), dict) and bool(current_brief.get("clarification_answers"))


def _auto_questions_for_intake(intake_confidence: Dict[str, str], existing: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    existing_fields = {str(question.get("field") or "").strip() for question in existing}
    questions = list(existing)

    for field in QUESTION_PRIORITY:
        if len(questions) >= 4:
            break
        if field in existing_fields:
            continue
        if intake_confidence.get(field) not in {"assumed", "missing"}:
            continue

        config = INTAKE_FIELDS[field]
        questions.append({
            "id": field,
            "field": field,
            "question": config["question"],
            "options": config["options"],
            "impact": config["impact"],
        })

    return questions[:4]


def _ensure_production_prompt_context(production_prompt: str, intake: Dict[str, str], resolved_choices: List[str]) -> str:
    lines = [production_prompt.strip()]

    required_lines = {
        "Subject priority:": intake["subject_priority"],
        "Clip selection priorities:": intake["clip_selection_bias"],
        "Quality tolerance:": intake["quality_tolerance"],
        "Text/caption direction:": intake["caption_strategy"],
        "Music sync:": intake["music_sync_style"],
        "Ending:": intake["ending_strategy"],
        "Resolved user choices:": "; ".join(resolved_choices) if resolved_choices else "Use the approved intake defaults.",
    }

    for label, value in required_lines.items():
        if label.lower() not in production_prompt.lower():
            lines.append(f"{label} {value}")

    return sanitize_plain_text("\n".join(line for line in lines if line), 2400)


